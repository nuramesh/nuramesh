// Generates src/generated.ts from openapi.json (R2.12). No dependencies: the schema subset the
// server emits (FastAPI/pydantic) is small, and the output must be byte-stable.
//
//   node scripts/generate.mjs          # rewrite src/generated.ts
//   node scripts/generate.mjs --check  # exit 1 if it is out of date
//
// Output is a pure function of openapi.json: sorted keys, fixed layout, no timestamps.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const OUT = join(root, "src", "generated.ts");

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const q = (s) => JSON.stringify(s);
const key = (s) => (IDENT.test(s) ? s : q(s));
const pascal = (s) =>
  s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");
const camel = (s) => {
  const p = pascal(s);
  return p[0].toLowerCase() + p.slice(1);
};
const typeName = (ref) => pascal(ref.replace("#/components/schemas/", ""));

/** A JSON-schema node as a TypeScript type expression. */
function ts(node, indent = "") {
  if (node === undefined || node === null || Object.keys(node).length === 0) return "unknown";
  if (node.$ref) return typeName(node.$ref);
  if (node.const !== undefined) return q(node.const);
  if (node.enum) return node.enum.map((v) => q(v)).join(" | ");
  const union = node.anyOf ?? node.oneOf;
  if (union) return [...new Set(union.map((n) => ts(n, indent)))].join(" | ");
  if (node.allOf) return node.allOf.map((n) => ts(n, indent)).join(" & ");
  const types = Array.isArray(node.type) ? node.type : [node.type];
  const parts = types.map((t) => {
    switch (t) {
      case "string":
        return "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array":
        return `${wrap(ts(node.items, indent))}[]`;
      case "object":
        return object(node, indent);
      default:
        return "unknown";
    }
  });
  return parts.join(" | ");
}
const wrap = (t) => (/[|&]/.test(t) ? `(${t})` : t);

function object(node, indent) {
  const props = node.properties ?? {};
  const names = Object.keys(props).sort();
  const extra = node.additionalProperties;
  if (names.length === 0) {
    if (extra && typeof extra === "object") return `Record<string, ${ts(extra, indent)}>`;
    return "Record<string, unknown>";
  }
  const req = new Set(node.required ?? []);
  const inner = `${indent}  `;
  const lines = names.map((n) => `${inner}${key(n)}${req.has(n) ? "" : "?"}: ${ts(props[n], inner)};`);
  if (extra && typeof extra === "object") lines.push(`${inner}[extra: string]: unknown;`);
  return `{\n${lines.join("\n")}\n${indent}}`;
}

function build(spec) {
  const out = [];
  out.push("// GENERATED by scripts/generate.mjs from openapi.json. Do not edit.");
  out.push("// Regenerate: uv run python scripts/sdk/dump_openapi.py && pnpm gen");
  out.push("/* eslint-disable */");
  out.push("");
  out.push('import type { IdempotencyHeaders, RequestOptions } from "./transport.js";');
  out.push("");
  out.push(`export const API_VERSION = ${q(spec.info.version)};`);
  out.push("");

  for (const name of Object.keys(spec.components?.schemas ?? {}).sort()) {
    const node = spec.components.schemas[name];
    const body = ts(node, "");
    const kind = body.startsWith("{") && !node.enum ? "interface" : "type";
    out.push(
      kind === "interface"
        ? `export interface ${typeName(name)} ${body}`
        : `export type ${typeName(name)} = ${body};`,
    );
    out.push("");
  }

  const methods = [];
  const paths = Object.keys(spec.paths).sort();
  for (const path of paths) {
    for (const verb of Object.keys(spec.paths[path]).sort()) {
      const op = spec.paths[path][verb];
      // One naming rule: the server's operation id is verb-first snake_case
      // from `nuramesh.server.operation_ids` and the method is its lowerCamelCase, nothing else.
      const id = op.operationId;
      if (!/^[a-z][a-z0-9]*(_[a-z0-9]+)*$/.test(id))
        throw new Error(`operation id ${id} (${verb.toUpperCase()} ${path}) is not snake_case`);
      const name = camel(id);
      const params = op.parameters ?? [];
      const group = (where) =>
        params
          .filter((p) => p.in === where)
          .sort((a, b) => a.name.localeCompare(b.name))
          .map((p) => ({ name: p.name, required: p.required === true, type: ts(p.schema) }));
      const pathP = group("path");
      const queryP = group("query");
      const headerP = group("header");
      const bodySchema = op.requestBody?.content?.["application/json"]?.schema;
      const bodyReq = op.requestBody?.required === true;
      const okCode = Object.keys(op.responses).find((c) => c.startsWith("2"));
      const resSchema = okCode
        ? op.responses[okCode].content?.["application/json"]?.schema
        : undefined;
      // The kill switch must work with the key ring or the store down: no
      // Idempotency-Key parameter on org halt and role pause (the server's ALWAYS_WORKS routes);
      // catalog pause keeps its optional key. The header's name lives in transport.ts.
      const killSwitch =
        verb === "post" && (path === "/v1/org/halt" || /^\/v1\/org\/roles\/\{[^/}]+\}\/pause$/.test(path));
      const fields = (list) => `{ ${list.map((p) => `${key(p.name)}${p.required ? "" : "?"}: ${p.type}`).join("; ")} }`;
      const argParts = [];
      if (pathP.length) argParts.push(`path: ${fields(pathP)}`);
      if (queryP.length)
        argParts.push(`query${queryP.some((p) => p.required) ? "" : "?"}: ${fields(queryP)}`);
      const headerRest = headerP.filter((p) => p.name.toLowerCase() !== "idempotency-key");
      const keyed = headerP.length > headerRest.length && !killSwitch;
      if (headerRest.length || keyed)
        argParts.push(
          `headers?: ${[keyed ? "IdempotencyHeaders" : "", headerRest.length ? fields(headerRest) : ""].filter(Boolean).join(" & ")}`,
        );
      if (bodySchema) argParts.push(`body${bodyReq ? "" : "?"}: ${ts(bodySchema)}`);
      const anyRequired = pathP.length > 0 || queryP.some((p) => p.required) || (bodySchema && bodyReq);
      const argsType = argParts.length ? `{ ${argParts.join("; ")} }` : null;
      const response = ts(resSchema);
      methods.push({
        name,
        verb,
        path,
        summary: op.summary,
        deprecated: op.deprecated === true,
        argsType,
        anyRequired,
        response,
        hasPath: pathP.length > 0,
      });
    }
  }
  const seen = new Set();
  for (const m of methods) {
    if (seen.has(m.name)) throw new Error(`duplicate method name ${m.name}`);
    seen.add(m.name);
  }

  out.push("/** Every operation: its HTTP verb and path template, for tests and tooling. */");
  out.push("export const OPERATIONS = {");
  for (const m of methods.sort((a, b) => a.name.localeCompare(b.name)))
    out.push(`  ${key(m.name)}: { method: ${q(m.verb.toUpperCase())}, path: ${q(m.path)} },`);
  out.push("} as const;");
  out.push("");
  out.push("/** The transport the generated methods call (implemented by NuraMeshClient). */");
  out.push("export interface Transport {");
  out.push(
    "  request<T>(method: string, path: string, args: { path?: object; query?: object; headers?: object; body?: unknown } | undefined, options: RequestOptions | undefined): Promise<T>;",
  );
  out.push("}");
  out.push("");
  out.push("/** Typed methods, one per operation. `NuraMeshClient` extends it. */");
  out.push("export abstract class GeneratedApi implements Transport {");
  out.push(
    "  abstract request<T>(method: string, path: string, args: { path?: object; query?: object; headers?: object; body?: unknown } | undefined, options: RequestOptions | undefined): Promise<T>;",
  );
  for (const m of methods) {
    out.push("");
    const tag = m.deprecated ? "\n   * @deprecated the route is deprecated; the summary names its successor\n   */" : " */";
    out.push(`  /** ${m.verb.toUpperCase()} ${m.path}${m.summary ? ` (${m.summary})` : ""}${tag}`);
    const arg = m.argsType ? `args${m.anyRequired ? "" : "?"}: ${m.argsType}, ` : "";
    out.push(`  ${m.name}(${arg}options?: RequestOptions): Promise<${m.response}> {`);
    out.push(
      `    return this.request<${m.response}>(${q(m.verb.toUpperCase())}, ${q(m.path)}, ${m.argsType ? "args" : "undefined"}, options);`,
    );
    out.push("  }");
  }
  out.push("}");
  out.push("");
  return out.join("\n");
}

const spec = JSON.parse(readFileSync(join(root, "openapi.json"), "utf8"));
const text = build(spec);
if (process.argv.includes("--check")) {
  if (existsSync(OUT) && readFileSync(OUT, "utf8") === text) process.exit(0);
  console.error("src/generated.ts is out of date: run `pnpm gen` in apps/sdk-ts");
  process.exit(1);
}
writeFileSync(OUT, text);
