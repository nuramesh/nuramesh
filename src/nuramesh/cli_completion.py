"""`nuramesh completion bash|zsh|fish` (R1.43).

Prints a static script generated from the argparse tree at the time of the call: commands,
subcommands, options and `choices`. It reads no store, opens no network connection and needs no
dependency. Hidden aliases are not parsers, so they are never completed.
"""

import argparse
import sys
from typing import Any

SHELLS = ("bash", "zsh", "fish")


def _tree(root: argparse.ArgumentParser) -> dict[str, dict[str, Any]]:
    """`{node path: {"words": [...], "choices": {option: [values]}}}` for every parser node."""
    nodes: dict[str, dict[str, Any]] = {}

    def walk(p: argparse.ArgumentParser, words: tuple[str, ...]) -> None:
        names: list[str] = []
        options: list[str] = []
        choices: dict[str, list[str]] = {}
        for action in p._actions:
            if isinstance(action, argparse._SubParsersAction):
                for name, child in action.choices.items():
                    names.append(name)
                    walk(child, (*words, name))
                continue
            if action.help == argparse.SUPPRESS:
                continue
            for opt in action.option_strings:
                options.append(opt)
                if action.choices:
                    choices[opt] = [str(c) for c in action.choices]
            if not action.option_strings and action.choices:
                names.extend(str(c) for c in action.choices)
        nodes[" ".join(words)] = {"words": names + sorted(options), "choices": choices}

    walk(root, ())
    return nodes


def _sh_quote(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"


def bash_script(root: argparse.ArgumentParser) -> str:
    """The bash completion script."""
    nodes = _tree(root)
    known = "|".join(_sh_quote(p) for p in nodes if p)
    cases = "\n".join(
        f"        {_sh_quote(path)}) opts={_sh_quote(' '.join(node['words']))};;"
        for path, node in nodes.items()
    )
    choice_cases = "\n".join(
        f"        {_sh_quote(path + '|' + opt)}) opts={_sh_quote(' '.join(values))};;"
        for path, node in nodes.items()
        for opt, values in node["choices"].items()
    )
    return f"""# bash completion for nuramesh (generated by `nuramesh completion bash`)
_nuramesh() {{
    local cur="${{COMP_WORDS[COMP_CWORD]}}" prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    local node="" w i opts=""
    for ((i = 1; i < COMP_CWORD; i++)); do
        w="${{COMP_WORDS[i]}}"
        [[ "$w" == -* ]] && continue
        case "${{node:+$node }}$w" in
            {known or "''"}) node="${{node:+$node }}$w";;
        esac
    done
    case "$node" in
{cases}
    esac
    case "$node|$prev" in
{choice_cases}
        *) ;;
    esac
    COMPREPLY=($(compgen -W "$opts" -- "$cur"))
}}
complete -F _nuramesh nuramesh
"""


def zsh_script(root: argparse.ArgumentParser) -> str:
    """The zsh completion script (put it in a `fpath` folder as `_nuramesh`)."""
    nodes = _tree(root)
    known = "|".join(_sh_quote(p) for p in nodes if p)
    cases = "\n".join(
        f"    {_sh_quote(path)}) opts=({' '.join(_sh_quote(w) for w in node['words'])});;"
        for path, node in nodes.items()
    )
    choice_cases = "\n".join(
        f"    {_sh_quote(path + '|' + opt)}) opts=({' '.join(_sh_quote(v) for v in values)});;"
        for path, node in nodes.items()
        for opt, values in node["choices"].items()
    )
    return f"""#compdef nuramesh
# zsh completion for nuramesh (generated by `nuramesh completion zsh`)
_nuramesh() {{
  local node="" w i
  local -a opts
  for ((i = 2; i < CURRENT; i++)); do
    w="${{words[i]}}"
    [[ "$w" == -* ]] && continue
    case "${{node:+$node }}$w" in
      {known or "''"}) node="${{node:+$node }}$w";;
    esac
  done
  case "$node" in
{cases}
  esac
  case "$node|${{words[CURRENT-1]}}" in
{choice_cases}
    *) ;;
  esac
  compadd -a opts
}}
_nuramesh "$@"
"""


def fish_script(root: argparse.ArgumentParser) -> str:
    """The fish completion script."""
    nodes = _tree(root)
    known = " ".join(_sh_quote(p) for p in nodes if p)
    lines = [
        "# fish completion for nuramesh (generated by `nuramesh completion fish`)",
        "function __nuramesh_node",
        "    set -l node",
        "    for w in (commandline -opc)[2..-1]",
        "        string match -q -- '-*' $w; and continue",
        '        set -l cand (string join " " $node $w)',
        f"        if contains -- $cand {known or chr(39) * 2}",
        "            set node $cand",
        "        end",
        "    end",
        '    string join " " $node',
        "end",
        "complete -c nuramesh -f",
    ]
    for path, node in nodes.items():
        cond = f'set -l n (__nuramesh_node); test "$n" = {_sh_quote(path)}'
        words = " ".join(w for w in node["words"] if not w.startswith("-"))
        if words:
            lines.append(f"complete -c nuramesh -n {_sh_quote(cond)} -a {_sh_quote(words)}")
        for opt in node["words"]:
            if opt.startswith("--"):
                values = node["choices"].get(opt)
                extra = f" -xa {_sh_quote(' '.join(values))}" if values else ""
                lines.append(f"complete -c nuramesh -n {_sh_quote(cond)} -l {opt[2:]}{extra}")
    return "\n".join(lines) + "\n"


def cmd_completion(args: argparse.Namespace) -> int:
    """Print the completion script for the chosen shell."""
    from nuramesh.cli import parser

    root = parser()
    script = {"bash": bash_script, "zsh": zsh_script, "fish": fish_script}[args.shell](root)
    sys.stdout.write(script)
    return 0


def add_parsers(sub: Any) -> None:
    """Register `completion bash|zsh|fish`."""
    comp = sub.add_parser("completion", help="print a shell completion script (bash, zsh or fish)")
    comp.add_argument("shell", choices=SHELLS, metavar="SHELL", help="bash, zsh or fish")
    comp.set_defaults(func=cmd_completion)
